/** the odds over time, 0 to 100% with the 50% line: real price points only (one per 10 min when it moved) */
function Chart({ points }: { points: number[] }) {
  const y = (p: number) => (4 + (1 - p) * 56).toFixed(1)
  const pts = points.map((p, i) => `${((i / (points.length - 1)) * 300).toFixed(1)},${y(p)}`).join(' ')
  return <div className="wk-chartbox"><span className="wk-ax num"><i>100%</i><i>50%</i><i>0%</i></span><svg className="wk-svg" viewBox="0 0 300 64" preserveAspectRatio="none" aria-label="The claim's odds over time"><line x1="0" x2="300" y1={y(0.5)} y2={y(0.5)} /><polyline points={pts} /></svg></div>
}

