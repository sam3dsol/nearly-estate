/** search any topic or paste a Wikipedia link: a page we have opens, any other Wikipedia title gets written now */
export function StartBox() {
  const nav = useNavigate()
  const [q, setQ] = useState('')
  const [hits, setHits] = useState<Suggestion[]>([])
  const [busy, setBusy] = useState<string | null>(null)
  const [msg, setMsg] = useState<string | null>(null)
  useEffect(() => {
    const s = q.trim(); if (s.length < 2 || /^https?:/.test(s)) { setHits([]); return }
    let on = true; const t = setTimeout(() => { get<Suggestion[]>(`/api/wiki/search?q=${encodeURIComponent(s)}`).then((x) => on && setHits(x)).catch(() => {}) }, 220)
    return () => { on = false; clearTimeout(t) }
  }, [q])
  const open = async (x: string) => {
    setMsg(null); setBusy(x)
    try { const r = await post<{ slug: string }>('/api/wiki/new', { q: x }); nav(`/wiki/${r.slug}`) } catch (e) { setMsg(friendlyError(e)) } finally { setBusy(null) }
  }
  // a question: the answer, its sources and a market to bet against; the market page shows all three
  const askIt = async (x: string) => {
    setMsg(null); setBusy('?')
    try { const r = await post<Ask>('/api/wiki/ask', { q: x }); if (r.market != null) nav(`/wiki/m/${r.market}`); else { setMsg(`${r.answer ? 'Yes' : 'No'}, the AI says ${Math.round(r.p * 100)}% likely: ${r.reason} No market opened for it yet (the daily cap or the fund).`); nav(`/wiki/${r.slug}`) } } catch (e) { setMsg(friendlyError(e)) } finally { setBusy(null) }
  }
  // always live; empty, it says what to type
  const go = (e: FormEvent) => { e.preventDefault(); const s = q.trim(); if (!s) { setMsg('Type a topic or a question first, then Open.'); return } const have = hits.find((h) => h.have && h.title.toLowerCase() === s.toLowerCase()); if (have) nav(`/wiki/${have.slug}`); else if (isQuestion(s)) askIt(s); else open(s) }
  return (
    <div className="wk-start">
      <form onSubmit={go} className="wk-search">
        <input className="mk-in" value={q} onChange={(e) => setQ(e.target.value)} placeholder="Ask anything, or any topic" aria-label="Search any topic" />
        <button type="submit" className="mk-btn auto" disabled={!!busy}>{busy === '?' ? 'Answering…' : busy ? 'Writing…' : 'Open'}</button>
      </form>
      {hits.length ? <div className="wk-hits">
        {hits.map((h) => (
          <button key={h.slug} type="button" className="wk-hit" disabled={!!busy} onClick={() => (h.have ? nav(`/wiki/${h.slug}`) : open(h.title))}>
            <span className="min-w-0"><span className="mk-name">{h.title}</span>{h.description ? <span className="mk-sub"> · {h.description}</span> : null}</span>
            <span className={`mk-state ${h.have ? 'open' : ''}`}>{busy === h.title ? 'Writing…' : h.have ? 'Read' : 'Write it'}</span>
          </button>
        ))}
      </div> : null}
      {msg ? <div className="mk-note wk-pad">{msg}</div> : null}
    </div>
  )
}

