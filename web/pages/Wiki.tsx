/* ---------- history: every version with why it was written, and the sentences that changed with the odds behind them ---------- */
type Version = { at: number; why: string; model?: string; summary: string; sections?: { h: string; body: string }[]; claims: string[]; prices: Record<string, [number, string]> | null }
type HistoryData = { current: { at: number; why: string } | null; versions: Version[] }
const unmark = (t: string) => t.replace(/\s*\[\d{1,2}\]/g, '').trim()
/** the sentence of a version that carries claim n's marker */
function sentenceOf(v: Version, n: number) {
  const all = [v.summary, ...(v.sections ?? []).map((x) => x.body)].join(' ').split(/(?<=[.!?\]])\s+(?=[A-Z0-9"'(“])/)
  const hit = all.find((x) => new RegExp(`\\[${n}\\]`).test(x))
  return hit ? unmark(hit) : null
}
type Change = { claim: string; before: string; after: string; p0: number | null; p1: number | null; moved: boolean }
/** the wording band of a price as the writer was told it (open markets only; a settled one is its ruling) */
const bandAt = (x: [number, string] | undefined) => (!x ? 'none' : x[1] !== 'Open' ? x[1] : x[0] >= 0.95 ? 'established' : x[0] >= 0.8 ? 'very likely' : x[0] >= 0.6 ? 'likely' : x[0] > 0.4 ? 'disputed' : x[0] > 0.2 ? 'unlikely' : x[0] > 0.05 ? 'very unlikely' : 'rejected')
/** what the newer version says differently about each claim, with the claim's odds when each was written */
function changes(newer: Version, older: Version, marketOf: (claim: string) => number | null): Change[] {
  const out: Change[] = []
  newer.claims.forEach((c, i) => {
    const j = older.claims.indexOf(c); if (j < 0) return
    const a = sentenceOf(older, j + 1), b = sentenceOf(newer, i + 1)
    if (!a || !b || a === b) return
    const m = marketOf(c)
    const x0 = m != null ? older.prices?.[m] : undefined, x1 = m != null ? newer.prices?.[m] : undefined
    const open = x0?.[1] === 'Open' && x1?.[1] === 'Open'
    out.push({ claim: c, before: a, after: b, p0: open ? x0![0] : null, p1: open ? x1![0] : null, moved: bandAt(x0) !== bandAt(x1) })
  })
  return out
}
export function History({ p }: { p: WPage }) {
  const [h, setH] = useState<HistoryData | null>(null)
  const ref = useRef(p.slug)
  useEffect(() => { ref.current = p.slug; get<HistoryData>(`/api/wiki/${encodeURIComponent(p.slug)}/history`).then((x) => ref.current === p.slug && setH(x)).catch(() => setH({ current: null, versions: [] })) }, [p.slug])
  if (!h) return <div className="mk-card skel short" />
  const byText = new Map(p.facts.map((f) => [f.claim, f.market]))
  const marketOf = (c: string) => byText.get(c) ?? null
  const now: Version = { at: p.updated, why: p.why || 'Current', summary: p.summary, sections: p.sections, claims: p.claims, prices: p.prices ?? null }
  const list = [now, ...h.versions]
  return (
    <div className="wk-hist">
      {list.map((v, i) => {
        const older = list[i + 1]
        const all = older ? changes(v, older, marketOf) : []
        // what the market moved leads; sentences only reworded are counted
        const ch = all.filter((c) => c.moved), reworded = all.length - ch.length
        return (
          <div key={`${v.at}-${i}`} className={`wk-ver${i === 0 ? ' now' : ''}`}>
            <span className="mk-mono mk-sub">{i === 0 ? `${timeAgo(v.at)} ago` : new Date(v.at).toLocaleString('en-US', { month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' })}</span>
            <span className="min-w-0">
              <span>{i === 0 ? <b>Current · </b> : null}{v.why}</span>
              {ch.map((c) => (
                <div key={c.claim} className="wk-diff">
                  <div className="mk-sub">{c.claim}{c.p0 != null && c.p1 != null ? <b className="mk-mono"> {pct(c.p0)} → {pct(c.p1)}</b> : null}</div>
                  <div className="wk-del">{c.before}</div>
                  <div className="wk-add">{c.after}</div>
                </div>
              ))}
              {older ? <div className="mk-sub">{ch.length ? '' : 'No claim changed its odds band. '}{reworded ? `${reworded} other sentence${reworded > 1 ? 's' : ''} reworded.` : ''}</div> : null}
            </span>
          </div>
        )
      })}
      {!h.versions.length ? <div className="mk-note">One version so far. A new one is written when a claim's odds move 10 points, when a claim is settled, or once a day, and this tab shows the sentences that changed.</div> : null}
    </div>
  )
}
