/** /wiki: "AI encyclopedia with prediction markets: instead of community curation, every fact becomes a perpetual truth-seeking
 *  market. The official pages are generated by AI based on the current market understanding." Any topic: the page
 *  is written from its Wikipedia article, every claim on it is a YES/NO market, and the wording follows the odds. */
export function Wiki() {
  const { token, id } = useParams()
  // /wiki/m/<id>: a market's own page; /wiki/me: the reader's bets; /wiki/hire: hire an AI agent to trade; /wiki/new: create a market
  if (id && /^\d+$/.test(id)) return <WikiClaim id={Number(id)} />
  return token === 'me' && !SOON.mine ? <WikiMine /> : token === 'hire' && !SOON.hire ? <WikiHire /> : token === 'new' ? <WikiCreate /> : token ? <WikiArticle slug={token} /> : <WikiGrid />
}

